int solve3(int n, int m) {
    if (n > m) {
        return solve3(m, n);
    }
    if (n == 1) {
        if ((m - 1) % 3 == 0) {
            return (m - 1) / 3 + 1;
        }
        return m;
    }
    if (n == 2) {
        if (m == 2 || m == 4) {
            return m*n;
        }
        if (m == 3) {
            return 2;
        }
        if (m == 5) {
            // return 3;
        }
        if (m == 6) {
            return 4;
        }
        return solve(n, m - 2) + 1;
    }
    if (n == 3) {
        if (m == 3) {
            return 3;
        }
        if (m == 4) {
            return 4;
        }
        if (m == 5) {
            return 4;
        }
        if (m == 6) {
            return 6;
        }
        return solve(n, m - 4) + 3;
    }
    if (n == 4) {
        if (m == 4) {
            return 4;
        }
        if (m == 5) {
            return 6;
        }
        if (m == 6) {
            return 7;
        }
        if (m == 7) {
            return 7;
        }
        return solve(n, m - 4) + 4;
    }

    if (n == 5) {
        if (m == 5) {
            return 7;
        }
        if (m == 6) {
            return 9;
        }
        if (m == 7) {
            return 10;
        }
        if (m == 8) {
            return 5+6;
        }
        return solve(n, m - 4) + 5;
    }
    if (n == 6) {
        if (m == 6) {
            return 10;
        }
        if (m == 7) {
            return 5+6;
        }
        if (m == 8) {
            return 3*4 + 1;
        }
        if (m == 9) {
            return 15;
        }
        if (m == 10) {
            return 16;
        }
        return solve(n, m-5) + 8;
    }
    if (n == 7) {
        if (m == 7) {
            return 6 * 2;
        }
        if (m == 8) {
            return 7 * 2;
        }
        if (m == 9) {
            return 7 * 2 + 3;
        }
        if (m == 10) {
            return 7 * 2 + 4;
        }
        return solve(n, m-4) + 7;
    }
    int res = n * m;
    return res;
}

